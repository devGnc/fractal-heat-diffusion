#define N_GLYPHS (int)(sizeof GLYPHS / sizeof GLYPHS[0])

static SDL_Texture *atlas;

int font_init(SDL_Renderer *ren) {
    SDL_SetHint(SDL_HINT_RENDER_SCALE_QUALITY, "0");  // pas de lissage
    SDL_Surface *surf = SDL_CreateRGBSurfaceWithFormat(0, N_GLYPHS * GW, GH, 32,
                                                       SDL_PIXELFORMAT_ARGB8888);
    if (!surf) return 0;
    SDL_FillRect(surf, NULL, 0x00000000);
    uint32_t *px = surf->pixels;
    int pitch = surf->pitch / 4;
    for (int g = 0; g < N_GLYPHS; g++) {
        for (int r = 0; r < GH; r++) {
            for (int c = 0; c < GW; c++) {
                if (GLYPHS[g].rows[r][c] == '#') px[r * pitch + g * GW + c] = 0xFFFFFFFF;
            }
        }
    }
    atlas = SDL_CreateTextureFromSurface(ren, surf);
    SDL_FreeSurface(surf);
    if (!atlas) return 0;
    SDL_SetTextureBlendMode(atlas, SDL_BLENDMODE_BLEND);
    return 1;
}

void font_free(void) {
    if (atlas) SDL_DestroyTexture(atlas);
    atlas = NULL;
}

// Décode le caractère UTF-8 suivant et avance le pointeur
static uint32_t next_cp(const char **s) {
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t cp;
    int n;
    if (p[0] < 0x80) { cp = p[0]; n = 1; }
    else if ((p[0] & 0xE0) == 0xC0) { cp = p[0] & 0x1F; n = 2; }
    else if ((p[0] & 0xF0) == 0xE0) { cp = p[0] & 0x0F; n = 3; }
    else { cp = p[0] & 0x07; n = 4; }
    for (int k = 1; k < n; k++) {
        if ((p[k] & 0xC0) != 0x80) { *s += k; return '?'; }
        cp = (cp << 6) | (p[k] & 0x3F);
    }
    *s += n;
    return cp;
}

static int glyph_index(uint32_t cp) {
    for (int g = 0; g < N_GLYPHS; g++) {
        if (GLYPHS[g].cp == cp) return g;
    }
    // Majuscules accentuées : on retombe sur la lettre simple
    if (cp >= 0xC8 && cp <= 0xCB) return glyph_index('E');
    if (cp >= 0xC0 && cp <= 0xC5) return glyph_index('A');
    return glyph_index('?');
}

int text_width(int scale, const char *s) {
    int n = 0;
    while (*s) { next_cp(&s); n++; }
    return n ? (n * ADV - 1) * scale : 0;
}

int text_height(int scale) {
    return GH * scale;
}

int text_draw(SDL_Renderer *ren, int x, int y, int scale, SDL_Color col, const char *s) {
    SDL_SetTextureColorMod(atlas, col.r, col.g, col.b);
    SDL_SetTextureAlphaMod(atlas, col.a);
    int x0 = x;
    while (*s) {
        int g = glyph_index(next_cp(&s));
        SDL_Rect src = { g * GW, 0, GW, GH };
        SDL_Rect dst = { x, y, GW * scale, GH * scale };
        SDL_RenderCopy(ren, atlas, &src, &dst);
        x += ADV * scale;
    }
    return x - x0;
}
